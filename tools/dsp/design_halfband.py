"""Design the three SushiDSP halfband stages with Parks-McClellan and emit the C++ header.

Usage:  python tools/dsp/design_halfband.py > include/SushiDSP/math/HalfbandCoefficients.hpp

The halfband structure is enforced after the equiripple design and the response is measured
again; see tools/dsp/README.md, "design_halfband.py".
"""
import sys
import numpy as np
import scipy
from scipy.signal import remez, freqz

STAGES = [
    ("kHalfbandStage1", 0.225,   90.0, "base <-> 2x, runs at 2*f_base; passband 0.45*f_base, stopband 0.55*f_base"),
    ("kHalfbandStage2", 0.1375,  90.0, "2x <-> 4x, runs at 4*f_base; passes 0.55*f_base, rejects its image at 1.45*f_base"),
    ("kHalfbandStage3", 0.06875, 90.0, "4x <-> 8x, runs at 8*f_base; passes 0.55*f_base, rejects its image at 3.45*f_base"),
]
GRID = 1 << 16


def enforce_halfband(h):
    n = len(h)
    centre = (n - 1) // 2
    h = h.copy()
    for i in range(n):
        if (i - centre) % 2 == 0 and i != centre:
            h[i] = 0.0
    h[centre] = 0.5
    others = h.sum() - 0.5
    scale = 0.5 / others
    for i in range(n):
        if i != centre:
            h[i] *= scale
    return h


def measure(h, passband_edge):
    w, response = freqz(h, worN=GRID, fs=1.0)
    magnitude_db = 20.0 * np.log10(np.maximum(np.abs(response), 1e-300))
    stop = magnitude_db[w >= 0.5 - passband_edge].max()
    ripple = np.abs(magnitude_db[w <= passband_edge]).max()
    return stop, ripple


def design(passband_edge, stopband_db):
    for m in range(2, 128):
        n = 4 * m - 1
        try:
            h = remez(n, [0.0, passband_edge, 0.5 - passband_edge, 0.5], [1.0, 0.0], fs=1.0,
                      maxiter=200, grid_density=32)
        except ValueError:
            continue
        h = enforce_halfband(h)
        stop, ripple = measure(h, passband_edge)
        if stop <= -stopband_db:
            return h, n, stop, ripple
    raise RuntimeError("no halfband length up to 511 taps met the stopband")


LICENCE_BLOCK_LINES = 7


def emit(out):
    header = open("include/SushiDSP/core/PortLayout.hpp", encoding="utf-8").read().split("\n")
    licence = header[:LICENCE_BLOCK_LINES]
    name_line = "/* HalfbandCoefficients.hpp"
    licence[1] = name_line + " " * (len(licence[0]) - len(name_line) - 2) + "*/"
    out.write("\n".join(licence) + "\n\n")
    out.write("// GENERATED by tools/dsp/design_halfband.py - do not edit by hand.\n")
    out.write(f"// scipy {scipy.__version__}, numpy {np.__version__}, remez grid_density=32, verification grid {GRID}.\n\n")
    out.write("#pragma once\n\n#include <cstdint>\n\nnamespace SushiDSP\n{\n")
    out.write("    /// @brief One halfband FIR stage: full symmetric impulse response with the zero taps\n")
    out.write("    /// stored as exact zeros and the centre tap exactly 0.5. Band edges are normalised to\n")
    out.write("    /// the stage's own higher sample rate.\n")
    out.write("    struct HalfbandDesign\n    {\n        const float*  taps;\n        std::uint32_t tap_count;\n")
    out.write("        float         passband_edge;\n        float         stopband_db;\n    };\n\n")
    for name, edge, want, note in STAGES:
        h, n, stop, ripple = design(edge, want)
        out.write(f"    // {note}\n")
        out.write(f"    // {n} taps; measured stopband {stop:.2f} dB, passband ripple {ripple:.5f} dB\n")
        out.write(f"    inline constexpr float {name}Taps[{n}] =\n    {{\n")
        for i in range(0, n, 4):
            row = ", ".join(f"{float(np.float32(v)):.9e}f" for v in h[i:i + 4])
            out.write(f"        {row},\n")
        out.write("    };\n")
        out.write(f"    inline constexpr HalfbandDesign {name}{{ {name}Taps, {n}u, {edge}f, {stop:.3f}f }};\n\n")
        print(f"{name}: {n} taps, stopband {stop:.2f} dB, ripple {ripple:.5f} dB", file=sys.stderr)
    out.write("}\n")


if __name__ == "__main__":
    emit(sys.stdout)
